#!/usr/bin/env node
/**
 * Generates the Docassemble interview YAML and the ALKiln feature file from the
 * same source the web screener uses.
 *
 *   "$LOCALAPPDATA/OpenAI/Codex/bin/node.exe" scripts/gen-docassemble.js
 *
 * Generated rather than transcribed for two reasons. The question wording is
 * still being revised by the author, so a hand-typed copy would be stale within
 * the week. And sixteen questions with help text and options is exactly the
 * volume where transcription errors hide.
 *
 * Variable names are the JavaScript ids unchanged (child14, housingFollowup,
 * substanceUse). They are all valid Python identifiers, camelCase and all, and
 * keeping them identical means the answers dict handed to the decision module
 * needs no translation layer that could itself be wrong.
 *
 * What this cannot do: run. There is no Docassemble server here, so the YAML is
 * reviewed code, not verified code. The decision logic underneath it IS verified;
 * see docassemble-snap-abawd/tests/test_snap_abawd_parity.py.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'docassemble-snap-abawd', 'docassemble', 'MLRISnapAbawd', 'data');
const S = require(path.join(ROOT, 'masslegalhelp', 'snap-screening-logic.js'));
const A = S.create('classic2');
const C = S.RESULT_COPY;
const NONE = S.NONE;

/** YAML double-quoted scalar. JSON string syntax is a valid subset. */
const y = s => JSON.stringify(String(s));

/** Help text to markdown: Docassemble renders help as markdown. */
function help(q) {
  const raw = q.helpHtml || q.help;
  if (!raw) return null;
  return String(raw)
    .replace(/\$\{LINKS\.([A-Za-z0-9_]+)\}/g, (m, k) => S.LINKS[k] || m)
    .replace(/<a [^>]*href="([^"]+)"[^>]*>(.*?)<\/a>/g, '[$2]($1)')
    .replace(/<br\s*\/?>\s*<br\s*\/?>/g, '\n\n')
    .replace(/<br\s*\/?>/g, '\n')
    .replace(/<\/?(strong|em)>/g, '**')
    .replace(/<[^>]+>/g, '')
    .replace(/\s*\n\s*/g, '\n')
    .trim();
}

/** Indent a block of text by n spaces, skipping empty lines. */
const indent = (text, n) => text.split('\n')
  .map(l => (l.trim() === '' ? '' : ' '.repeat(n) + l)).join('\n');

function fieldFor(q) {
  const out = [];
  const label = y(q.text);
  if (q.type === 'yn') {
    out.push('  - ' + label + ': ' + q.id);
    out.push('    datatype: yesnoradio');
  } else if (q.type === 'multi') {
    out.push('  - ' + label + ': ' + q.id);
    out.push('    datatype: checkboxes');
    out.push('    choices:');
    q.options.forEach(o => out.push('      - ' + y(o.label) + ': ' + o.id));
    /* An explicit none choice, not Docassemble's "none of the above".
     * The decision logic treats "none of these apply" and "nothing checked" as
     * opposite answers, and the built-in none-of-the-above gives no distinct
     * value to tell them apart. See DECISION-SPEC.md, housing table. */
    out.push('      - ' + y(q.noneLabel) + ': ' + y(NONE));
  } else if (q.type === 'single') {
    out.push('  - ' + label + ': ' + q.id);
    out.push('    datatype: radio');
    out.push('    choices:');
    q.options.forEach(o => out.push('      - ' + y(o.label) + ': ' + o.id));
    out.push('      - ' + y(q.noneLabel) + ': ' + y(NONE));
  }
  // Every question is optional. This also keeps the variable defined, so the
  // decision code never triggers a question of its own.
  out.push('    required: False');
  const h = help(q);
  if (h) {
    out.push('    help: |');
    out.push(indent(h, 6));
  } else if (q.listItems && q.listItems.length) {
    out.push('    help: |');
    out.push(indent(q.listItems.map(li => '- ' + li).join('\n'), 6));
  }
  if (q.showIf) {
    out.push('    show if:');
    out.push('      variable: ' + q.showIf.id);
    out.push('      is: ' + y(q.showIf.val));
  }
  return out.join('\n');
}

const blocks = [];

blocks.push(`# Generated by scripts/gen-docassemble.js in the MLRI source repository.
# Do not hand-edit: regenerate instead, or the wording drifts from the web
# screener and from SCREENER-COPY.md, which is what the author reviews.
#
# Not yet run against a Docassemble server. Reviewed code, not verified code.
# The decision logic it calls IS verified against the JavaScript reference by
# tests/test_snap_abawd_parity.py.
---
metadata:
  title: SNAP Work Rules Screening
  short title: SNAP work rules
  authors:
    - Massachusetts Law Reform Institute
  description: |
    Checks whether the Massachusetts DTA ABAWD work rules apply to someone
    getting SNAP, or whether they may be exempt or have good cause.
---
# Court Forms Online hosts through the Document Assembly Line. Turning the
# include below on brings AssemblyLine branding, ALDocument, and the tested
# question library. Left off so this file runs on a plain Docassemble server
# without the dependency, which makes it easier to try.
#
# include:
#   - docassemble.AssemblyLine:al_package.yml
modules:
  - .snap_abawd
---
features:
  question help button: True
  progress bar: True
---
mandatory: True
code: |
  introduction
  family_group
  health_group
  benefits_group
  school_work_group
  # Deliberately tested against partial_answers, not collected_answers.
  # collected_answers includes goodcause, so asking it here would need the
  # answer before deciding whether to ask the question. Nothing that decides
  # the skip depends on goodcause: only an exempt outcome skips it.
  if should_skip_good_cause(partial_answers):
    goodcause = None
  else:
    good_cause_group
  if outcome in ('exempt', 'goodcause'):
    statement_details
  results_screen
---
# Everything except goodcause. Used for the skip decision above.
code: |
  partial_answers = {
${A.QUESTIONS.map(q => "    '" + q.id + "': " + q.id + ",").join('\n')}
  }
---
# The full set, handed to the decision module. Variable names are the only
# mapping between interview and logic, and they are identical on both sides.
code: |
  collected_answers = dict(partial_answers)
  collected_answers['goodcause'] = goodcause
---
code: |
  outcome = result_type(collected_answers)
---
code: |
  reasons = exempt_reasons(collected_answers)
---`);

/* ---- Start screen ----
 * Read from the shipping page, not typed here. These four strings were hardcoded
 * until 2026-07-30, when the author changed the age range and the interview kept
 * saying "18 through 64" while both web builds said otherwise. Nothing caught it,
 * because a copy of a string cannot be checked against its original. */
const SHIP_HTML = fs.readFileSync(
  path.join(ROOT, 'masslegalhelp', 'tools', 'snap-abawd', 'index.html'), 'utf8');

function fromShippingPage(id, re) {
  const m = SHIP_HTML.match(re);
  if (!m) {
    console.error('gen-docassemble: could not find ' + id + ' in masslegalhelp/tools/snap-abawd/index.html.');
    console.error('Fix the pattern here rather than pasting the text in, or the interview');
    console.error('and the web builds drift apart silently.');
    process.exit(1);
  }
  /* The intro paragraph is built in the page from static markup plus
   * RESULT_COPY.introExemptExplain, so it arrives with one template expression in
   * it. Expanded before conversion, which is what lets that paragraph be read from
   * the page like the other three instead of pasted in below. */
  const raw = m[1].replace('${esc(RESULT_COPY.introExemptExplain)}', C.introExemptExplain);
  // Same conversion the help text gets: links and emphasis to markdown.
  return help({ help: raw });
}

const introSummary = fromShippingPage('introSummary', /<p [^>]*>(Some adults on SNAP who are[\s\S]*?)<\/p>/);
const timeEstimate = fromShippingPage('timeEstimate', /<p [^>]*>(This short online form asks[\s\S]*?)<\/p>/);
const privacyIntro = `**${C.privacyIntroLead}** ${C.privacyIntroBody}`;
const pageH1 = fromShippingPage('h1', /<h1 class="h1">([^<]+)<\/h1>/);

blocks.push(`question: |
${indent(pageH1, 2)}
subquestion: |
${indent(introSummary, 2)}

${indent(timeEstimate, 2)}

${indent(privacyIntro, 2)}
continue button field: introduction
---`);

/* ---- One page per group ---- */
const GROUP_VARS = ['family_group', 'health_group', 'benefits_group', 'school_work_group'];
A.GROUPS.forEach((g, i) => {
  const fields = g.ids.map(id => A.Q_BY_ID[id]).filter(Boolean).map(fieldFor).join('\n');
  // The author asked for the optional-questions line on the first group only.
  const sub = i === 0
    ? 'subquestion: |\n  Answer any that apply to you. Every question is optional.\n'
    : '';
  blocks.push(`question: ${y(g.title)}
${sub}fields:
${fields}
continue button field: ${GROUP_VARS[i]}
---`);
});

/* ---- Good cause ---- */
const gc = A.GOODCAUSE;
const gcHelp = help(gc);
blocks.push(`question: ${y(gc.text)}
fields:
  - ${y(gc.text)}: goodcause
    datatype: radio
    choices:
${gc.options.map(o => '      - ' + y(o.label) + ': ' + o.id).join('\n')}
      - ${y(gc.noneLabel)}: ${y(NONE)}
    required: False${gcHelp ? '\n    help: |\n' + indent(gcHelp, 6) : ''}
continue button field: good_cause_group
---`);

/* ---- Result screens ---- */
blocks.push(`event: results_screen
question: |
  % if outcome == 'exempt':
  ${C.exemptHeading}
  % elif outcome == 'goodcause':
  ${C.goodCauseHeading}
  % else:
  ${C.notExemptHeading}
  % endif
subquestion: |
  % if outcome == 'exempt':
  % for reason in reasons:
  * \${ reason }
  % endfor

  ${C.formLeadExempt}
  % elif outcome == 'goodcause':
  ${C.goodCauseIntro}

  ${C.formLeadGoodCause}
  % else:
  ${C.notExemptIntro}

  ${C.workRulesHeading}
  % endif

  **${C.privacyIntroLead}** ${C.privacyIntroBody}
attachment code: tell_dta_statement if outcome in ('exempt', 'goodcause') else []
buttons:
  - Start over: restart
---`);

/* ---- The statement, as an inline attachment ----
 * Markdown content rather than a DOCX template, so the package carries no binary
 * and can be reviewed as text. Filling DTA's own self-declaration PDF would suit
 * the Assembly Line pipeline better and is the recommended next step. */
blocks.push(`attachment:
  name: SNAP Work Rules Statement
  filename: snap-work-rules-statement
  valid formats:
    - pdf
    - docx
  variable name: tell_dta_statement
  content: |
    # SNAP Work Rules Statement

    Your name: \${ client_name if defined('client_name') else '' }

    Client / Agency ID (if you have one): \${ agency_id if defined('agency_id') else '' }

    % if outcome == 'exempt':
    I believe I do not have to meet the ABAWD work rules for these reasons:

    % for reason in reasons:
    * \${ reason }
    % endfor
    % else:
    I could not meet the ABAWD work rules for this reason:

    * \${ good_cause_text }
    % endif

    In my own words:

    \${ explanation if defined('explanation') else '' }

    Signature: ______________________________  Date: \${ today() }
---
question: |
  Add your details to the statement
fields:
  - Your name: client_name
    required: False
  - Client / Agency ID (if you have one): agency_id
    required: False
  - In a few sentences: explanation
    datatype: area
    required: False
continue button field: statement_details
---
code: |
  good_cause_text = good_cause_statement_text(goodcause)
---`);

fs.mkdirSync(path.join(OUT_DIR, 'questions'), { recursive: true });
fs.mkdirSync(path.join(OUT_DIR, 'sources'), { recursive: true });

/* Trailing "---" leaves an empty final document, which Docassemble rejects. */
const yaml = blocks.join('\n')
  .replace(/\n{3,}/g, '\n\n')
  .replace(/---\n---/g, '---')
  .replace(/\n---\s*$/, '') + '\n';
fs.writeFileSync(path.join(OUT_DIR, 'questions', 'snap_abawd.yml'), yaml, 'utf8');

/* ---- ALKiln feature file, from the same worked examples the parity test uses ---- */
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, 'decision-spec.json'), 'utf8'));
const feat = [];
feat.push('# Generated by scripts/gen-docassemble.js from decision-spec.json.');
feat.push('# The same worked examples the Python parity test uses, expressed for ALKiln.');
feat.push('# Not run: ALKiln needs a Docassemble server.');
feat.push('');
feat.push('Feature: SNAP work rules screening reaches the right outcome');
feat.push('');
for (const ex of spec.examples) {
  const set = Object.entries(ex.answers)
    .map(([k, v]) => '      | ' + k + ' | ' + (Array.isArray(v) ? v.join(',') : String(v)) + ' |');
  feat.push('  Scenario: ' + ex.name);
  feat.push('    Given I start the interview at "snap_abawd.yml"');
  if (set.length) {
    feat.push('    And I set the variables to these values');
    feat.push('      | var | value |');
    feat.push(...set);
  }
  feat.push('    Then the variable "outcome" should be "' + ex.expect.outcome + '"');
  feat.push('');
}
fs.writeFileSync(path.join(OUT_DIR, 'sources', 'snap_abawd.feature'), feat.join('\n') + '\n', 'utf8');

console.log('Wrote the interview and the ALKiln feature file.');
console.log('  ' + A.QUESTIONS.length + ' questions across ' + A.GROUPS.length + ' pages');
console.log('  ' + spec.examples.length + ' ALKiln scenarios');
console.log('  NOT run against a Docassemble server; the YAML is unverified.');
